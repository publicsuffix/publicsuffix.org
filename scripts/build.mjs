// Builds the site stylesheet from Sass, using Mozilla Protocol as a library.
//
//   src/scss/site.scss  ->  styles.css
//
// Protocol fonts and images referenced by the compiled CSS are copied into
// assets/protocol/, so the site stays fully static and has no third-party
// requests. The output is committed to the repository: the deploy workflow
// publishes the repository as-is and runs no build step.

import { createRequire } from 'node:module';
import { cpSync, existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as sass from 'sass';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const protocolDir = join(
  dirname(require.resolve('@mozilla-protocol/core/package.json')),
  'protocol',
);
const protocolVersion = require('@mozilla-protocol/core/package.json').version;

const entry = join(root, 'src/scss/site.scss');
const outCss = join(root, 'styles.css');
const assetsDir = join(root, 'assets/protocol');

const { css } = sass.compile(entry, {
  loadPaths: [join(protocolDir, 'css')],
  style: 'compressed',
  // Sass would emit a BOM; an explicit @charset is written below instead so
  // the banner comment can follow it.
  charset: false,
  // Protocol still uses some deprecated Sass APIs internally.
  quietDeps: true,
  silenceDeprecations: ['import'],
});

const banner =
  `@charset "UTF-8";\n` +
  `/* Generated by scripts/build.mjs from src/scss/ - do not edit directly.\n` +
  `   Mozilla Protocol ${protocolVersion} (MPL-2.0): https://protocol.mozilla.org/ */\n`;
writeFileSync(outCss, banner + css + '\n');

// Copy every Protocol asset the compiled CSS points to.
rmSync(assetsDir, { recursive: true, force: true });
const urls = [...css.matchAll(/url\(["']?([^"')]+)["']?\)/g)]
  .map((m) => m[1])
  .filter((u) => u.startsWith('assets/protocol/'));

for (const url of new Set(urls)) {
  const rel = url.slice('assets/protocol/'.length);
  const src = join(protocolDir, rel);
  if (!existsSync(src)) {
    throw new Error(`Asset referenced by CSS not found in Protocol: ${rel}`);
  }
  const dest = join(assetsDir, rel);
  mkdirSync(dirname(dest), { recursive: true });
  cpSync(src, dest);
}
cpSync(join(protocolDir, '..', 'LICENSE'), join(assetsDir, 'LICENSE'));

console.log(
  `Built ${relative(root, outCss)} and copied ${new Set(urls).size} assets to ${relative(root, assetsDir)}/`,
);
