// Checks run by `npm test`. Run `npm run build` first if src/scss/ changed.

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');

const pages = {
  'index.html': null,
  'learn/index.html': '/learn/',
  'list/index.html': '/list/',
  'submit/index.html': '/submit/',
};

for (const [page, current] of Object.entries(pages)) {
  test(`${page}: links the site stylesheet and keeps the shared layout`, () => {
    const html = read(page);
    assert.match(html, /<link rel="stylesheet" href="\/styles\.css">/);
    for (const href of ['/learn/', '/list/', '/submit/']) {
      assert.ok(html.includes(`<a href="${href}"`), `nav link to ${href}`);
    }
    assert.match(html, /<footer class="mzp-c-footer">/);
    assert.match(html, /Mozilla Foundation<\/a>/);
  });

  test(`${page}: marks only its own nav item as current`, () => {
    const marked = [...read(page).matchAll(/<a href="([^"]+)" aria-current="page">/g)].map((m) => m[1]);
    assert.deepEqual(marked, current ? [current] : []);
  });

  test(`${page}: loads no third-party resources and only the footer-year script`, () => {
    const html = read(page);
    const scripts = [...html.matchAll(/<script\b[^>]*>/gi)].map((m) => m[0]);
    assert.deepEqual(scripts, ['<script src="/assets/js/current-year.js" defer>']);
    assert.doesNotMatch(html, /<link[^>]+href="(https?:)?\/\//i);
  });

  test(`${page}: footer copyright end year is filled in from the current year`, () => {
    assert.match(
      read(page),
      /Copyright &#169; 2007&#8211;<span data-current-year>\d{2}<\/span> <a href="https:\/\/www\.mozilla\.org\/">Mozilla Foundation<\/a>\./,
    );
  });
}

// Many clients fetch the list from this URL, relative to /list/.
test('list page links to public_suffix_list.dat', () => {
  assert.match(read('list/index.html'), /href="public_suffix_list\.dat"/);
});

test('current-year.js writes the two-digit current year', async () => {
  const els = [{ textContent: '00' }, { textContent: '00' }];
  globalThis.document = { querySelectorAll: (sel) => (sel === '[data-current-year]' ? els : []) };
  try {
    await import(`../assets/js/current-year.js?${Date.now()}`);
  } finally {
    delete globalThis.document;
  }
  const yy = String(new Date().getFullYear()).slice(-2);
  assert.deepEqual(els.map((e) => e.textContent), [yy, yy]);
});

test('robots.txt is unchanged', () => {
  assert.equal(read('robots.txt'), 'User-agent: *\nDisallow: /images/');
});

test('styles.css is generated and every asset it references exists', () => {
  const css = read('styles.css');
  assert.match(css, /Generated by scripts\/build\.mjs/);
  const urls = [...css.matchAll(/url\(["']?([^"')]+)["']?\)/g)]
    .map((m) => m[1])
    .filter((u) => !u.startsWith('data:'));
  assert.ok(urls.length > 0);
  for (const url of urls) {
    assert.ok(!/^(https?:)?\/\//.test(url), `no remote asset: ${url}`);
    assert.ok(existsSync(join(root, url)), `missing asset: ${url}`);
  }
});
